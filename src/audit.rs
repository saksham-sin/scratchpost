//! Living audit ledger.
//!
//! `scratchpostd` performs coordination work that no human watches: it provisions
//! worktrees, allocates port bands, blocks colliding commits, and releases
//! barriers. This module turns that work into `RUNNING_REPORT.md` at the master
//! root so a developer returning to the workspace can see exactly what happened
//! while they were away.
//!
//! Two files are involved:
//!
//! * `.scratchpost/audit.log` — append-only JSONL, one `Notice` per line. This is
//!   the durable record; it survives daemon restarts and is not capped.
//! * `RUNNING_REPORT.md` — regenerated atomically from the tail of the log plus a
//!   live telemetry table. Never hand-edited.
//!
//! The daemon is the only writer, so no locking is required beyond the atomic
//! rename in [`workspace::atomic_write`].

use crate::protocol::{LedgerSnapshot, Notice, Severity};
use crate::workspace;
use std::fs::{self, OpenOptions};
use std::io::Write;
use std::path::{Path, PathBuf};

/// Report file name, relative to the master root.
pub const REPORT_FILE: &str = "RUNNING_REPORT.md";

/// How many audit entries the rendered report shows. The log on disk keeps
/// everything; the report is a window, not an archive.
const MAX_RENDERED_ENTRIES: usize = 120;

pub fn log_path(master: &Path) -> PathBuf {
    workspace::state_dir(master).join("audit.log")
}

/// Appends one coordination action to the durable audit log.
///
/// Failures are swallowed by the caller: an audit write must never take down the
/// daemon or fail a commit. The report is a convenience, not a correctness
/// boundary.
pub fn record(master: &Path, notice: &Notice) -> std::io::Result<()> {
    let path = log_path(master);
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)?;
    }
    let line = serde_json::to_string(notice).map_err(std::io::Error::other)?;
    let mut file = OpenOptions::new().create(true).append(true).open(&path)?;
    file.write_all(line.as_bytes())?;
    file.write_all(b"\n")?;
    Ok(())
}

/// Reads the tail of the audit log. Malformed lines are skipped rather than
/// aborting the render: a truncated final line after a crash must not blank the
/// report.
fn read_tail(master: &Path, limit: usize) -> Vec<Notice> {
    let Ok(text) = fs::read_to_string(log_path(master)) else {
        return Vec::new();
    };
    let mut entries: Vec<Notice> = text
        .lines()
        .filter(|line| !line.trim().is_empty())
        .filter_map(|line| serde_json::from_str::<Notice>(line).ok())
        .collect();
    if entries.len() > limit {
        entries.drain(..entries.len() - limit);
    }
    entries
}

/// `HH:MM:SS` in UTC. Deterministic and timezone-independent, which matters
/// because the report is committed and diffed.
fn clock(ms: u64) -> String {
    let secs = ms / 1000 % 86_400;
    format!(
        "{:02}:{:02}:{:02}",
        secs / 3600,
        (secs % 3600) / 60,
        secs % 60
    )
}

fn severity_label(severity: &Severity) -> &'static str {
    match severity {
        Severity::Info => "info",
        Severity::Warning => "warn",
        Severity::Blocking => "block",
    }
}

/// Renders the report. Pure function of the snapshot plus the audit log tail, so
/// it is trivially testable.
pub fn render(master: &Path, snapshot: &LedgerSnapshot) -> String {
    let entries = read_tail(master, MAX_RENDERED_ENTRIES);
    let active = snapshot
        .sessions
        .iter()
        .filter(|session| session.status == crate::protocol::SessionStatus::Active)
        .count();
    let committed = snapshot
        .claims
        .iter()
        .filter(|claim| claim.state == crate::protocol::ClaimState::Committed)
        .count();
    let reserved = snapshot.claims.len() - committed;
    let open_barriers = snapshot
        .barriers
        .iter()
        .filter(|barrier| barrier.open)
        .count();

    let mut out = String::new();
    out.push_str("# ScratchPost — Running Report\n\n");
    out.push_str(
        "> Generated by `scratchpostd`. Do not edit by hand: this file is rewritten\n\
         > atomically on every coordination action.\n\n",
    );

    out.push_str("## Telemetry\n\n");
    out.push_str("| Metric | Value |\n|---|---|\n");
    out.push_str(&format!(
        "| coordination mode | `{}` |\n",
        snapshot.config.mode
    ));
    out.push_str(&format!(
        "| barrier scope | `{}` |\n",
        match snapshot.config.barrier_scope {
            crate::protocol::BarrierScope::Workspace => "workspace",
            crate::protocol::BarrierScope::Component => "component",
        }
    ));
    out.push_str(&format!("| daemon pid | `{}` |\n", snapshot.daemon_pid));
    out.push_str(&format!("| active agents | {} |\n", active));
    out.push_str(&format!(
        "| sequence claims | {} committed, {} reserved |\n",
        committed, reserved
    ));
    out.push_str(&format!("| open barriers | {} |\n", open_barriers));
    out.push_str(&format!(
        "| conflict components | {} |\n",
        snapshot.components.len()
    ));
    out.push_str(&format!("| audit entries | {} |\n\n", entries.len()));

    if !snapshot.sessions.is_empty() {
        out.push_str("## Agent Lanes\n\n");
        out.push_str("| Agent | Status | Slot | Port base | Branch |\n|---|---|---:|---:|---|\n");
        for session in &snapshot.sessions {
            let branch = session
                .repos
                .first()
                .map(|repo| repo.branch.as_str())
                .unwrap_or("-");
            out.push_str(&format!(
                "| `{}` | {} | {} | {} | `{}` |\n",
                session.agent,
                match session.status {
                    crate::protocol::SessionStatus::Active => "active",
                    crate::protocol::SessionStatus::Abandoned => "abandoned",
                },
                session.slot,
                session.port_base,
                branch
            ));
        }
        out.push('\n');
    }

    if !snapshot.claims.is_empty() {
        out.push_str("## Sequence Registry\n\n");
        out.push_str("| Agent | Rule | Namespace | Key | State |\n|---|---|---|---:|---|\n");
        for claim in &snapshot.claims {
            out.push_str(&format!(
                "| `{}` | `{}` | `{}` | {} | {} |\n",
                claim.agent,
                claim.rule,
                claim.namespace,
                claim.key,
                match claim.state {
                    crate::protocol::ClaimState::Committed => "committed",
                    crate::protocol::ClaimState::Reserved => "reserved",
                    crate::protocol::ClaimState::Released => "released",
                }
            ));
        }
        out.push('\n');
    }

    out.push_str("## Event Log\n\n");
    if entries.is_empty() {
        out.push_str("_No coordination actions recorded yet._\n");
    } else {
        out.push_str("Newest first. `block` entries are the ones that stopped an agent.\n\n");
        out.push_str("```text\n");
        for notice in entries.iter().rev() {
            let agent = notice.agent.as_deref().unwrap_or("system");
            out.push_str(&format!(
                "[{}] {:<5} {:<12} {}\n",
                clock(notice.created_ms),
                severity_label(&notice.severity),
                agent,
                notice.message
            ));
        }
        out.push_str("```\n");
    }

    out
}

/// Regenerates `RUNNING_REPORT.md` atomically. Called from the daemon's publish
/// path, so it runs at most once per state change.
pub fn write_report(master: &Path, snapshot: &LedgerSnapshot) -> std::io::Result<()> {
    let text = render(master, snapshot);
    workspace::atomic_write(&master.join(REPORT_FILE), text.as_bytes())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::protocol::{Config, Notice, Severity};

    fn notice(
        seq: u64,
        severity: Severity,
        kind: &str,
        agent: Option<&str>,
        message: &str,
    ) -> Notice {
        Notice {
            seq,
            severity,
            kind: kind.to_string(),
            agent: agent.map(ToString::to_string),
            message: message.to_string(),
            created_ms: 1_700_000_000_000 + seq * 1000,
        }
    }

    fn snapshot() -> LedgerSnapshot {
        LedgerSnapshot {
            daemon_pid: 4242,
            started_ms: 1_700_000_000_000,
            master_root: "/tmp/sp-audit".to_string(),
            config: Config::default(),
            sessions: Vec::new(),
            claims: Vec::new(),
            intents: Vec::new(),
            notices: Vec::new(),
            barrier: Default::default(),
            barriers: Vec::new(),
            components: Vec::new(),
            path_claims: Vec::new(),
        }
    }

    #[test]
    fn clock_is_utc_and_zero_padded() {
        assert_eq!(clock(0), "00:00:00");
        assert_eq!(clock(1_700_000_000_000), "22:13:20");
        assert_eq!(clock(86_400_000), "00:00:00");
    }

    #[test]
    fn record_appends_and_render_shows_newest_first() {
        let root = std::env::temp_dir().join(format!("sp-audit-{}", std::process::id()));
        let _ = fs::remove_dir_all(&root);
        fs::create_dir_all(workspace::state_dir(&root)).unwrap();

        record(
            &root,
            &notice(
                1,
                Severity::Info,
                "session-active",
                Some("agent_1"),
                "agent_1 attached",
            ),
        )
        .unwrap();
        record(
            &root,
            &notice(
                2,
                Severity::Blocking,
                "commit-blocked",
                Some("agent_2"),
                "200 is reserved by agent_1 for auth-service:dbchangelog.xml",
            ),
        )
        .unwrap();

        let text = render(&root, &snapshot());
        assert!(text.contains("## Event Log"));
        assert!(text.contains("agent_2"));
        assert!(text.contains("200 is reserved by agent_1"));
        // Newest first: the blocking entry precedes the attach entry.
        let blocked = text.find("200 is reserved").unwrap();
        let attached = text.find("agent_1 attached").unwrap();
        assert!(blocked < attached, "event log must be newest-first");
        assert!(text.contains("| audit entries | 2 |"));

        let _ = fs::remove_dir_all(&root);
    }

    #[test]
    fn malformed_log_lines_are_skipped() {
        let root = std::env::temp_dir().join(format!("sp-audit-bad-{}", std::process::id()));
        let _ = fs::remove_dir_all(&root);
        fs::create_dir_all(workspace::state_dir(&root)).unwrap();
        record(
            &root,
            &notice(1, Severity::Info, "daemon-started", None, "daemon started"),
        )
        .unwrap();
        // Simulate a crash mid-append.
        let mut file = OpenOptions::new()
            .append(true)
            .open(log_path(&root))
            .unwrap();
        file.write_all(b"{\"seq\":2,\"severity\":\"inf").unwrap();

        let text = render(&root, &snapshot());
        assert!(text.contains("daemon started"));
        assert!(text.contains("| audit entries | 1 |"));

        let _ = fs::remove_dir_all(&root);
    }

    #[test]
    fn empty_log_renders_a_placeholder() {
        let root = std::env::temp_dir().join(format!("sp-audit-empty-{}", std::process::id()));
        let _ = fs::remove_dir_all(&root);
        fs::create_dir_all(workspace::state_dir(&root)).unwrap();
        let text = render(&root, &snapshot());
        assert!(text.contains("_No coordination actions recorded yet._"));
        let _ = fs::remove_dir_all(&root);
    }
}
